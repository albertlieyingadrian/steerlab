"""Recipe R5: Enhanced mining sampling with expanded hard case coverage.

Mining: 4000 pages from the most challenging score range (0.25-0.75) around the decision boundary,
focusing on borderline cases that are harder to classify. Includes both central borderline cases
and extreme cases near the boundaries to improve robustness.
Mirrors: 500 AI rewrites of mining pages, to add more variety in AI styles.
Replay: 6000 random rows from the detector's own training data (data v2b) with their
own labels and weights, to maintain knowledge of the original distribution.
1.5 epochs at learning rate 2.5e-4.
Cutoff: the 99th percentile of the updated detector's scores on data v2b's validation humans.
"""

import json
from pathlib import Path

import numpy as np

HUMAN_W = 1.3278
K_HARD = 4000  # Increased from 3449 to get more samples from hard regions
N_REPLAY = 6000  # Reduced from 6497 to make room for more mining
N_MIRRORS = 500


def build(ctx):
    data = Path(ctx["data"])
    scores = np.load(data / "mining_scores_r0.npy")
    
    # Sample from a wider score range (0.25-0.75) to capture both central borderline cases
    # and extreme cases near the boundaries
    mask = (scores >= 0.25) & (scores <= 0.75)
    indices_in_range = np.where(mask)[0]
    
    # Shuffle and take first K_HARD samples
    rng = np.random.default_rng(0)
    selected_indices = rng.choice(indices_in_range, min(K_HARD, len(indices_in_range)), replace=False)
    rng.shuffle(selected_indices)
    
    # Take first K_HARD samples (or all if less than K_HARD)
    mining_indices = selected_indices[:K_HARD]
    rows = [{"pool": "mining", "idx": int(i), "bucket": 0, "weight": HUMAN_W} for i in mining_indices]

    # Add mirror samples
    with open(data / "mirrors.jsonl") as f:
        mirrors = []
        for line in f:
            r = json.loads(line)
            mirrors.append(r)
    
    # Sample mirrors randomly
    rng = np.random.default_rng(0)
    mirror_indices = sorted(rng.choice(len(mirrors), N_MIRRORS, replace=False))
    for i in mirror_indices:
        r = mirrors[i]
        rows.append({"pool": "mirrors", "idx": int(i), "bucket": 3, "weight": 1.3092})

    # Add replay samples
    meta = []
    with open(data / "replay.jsonl") as f:
        for line in f:
            r = json.loads(line)
            meta.append((int(r["bucket"]), float(r["weight"])))
    rng = np.random.default_rng(0)
    for i in sorted(rng.choice(len(meta), N_REPLAY, replace=False)):
        b, w = meta[i]
        rows.append({"pool": "replay", "idx": int(i), "bucket": b, "weight": w})
        
    return {"rows": rows, "train": {"lr": 2.5e-4, "epochs": 1.5}, "note": "R5: enhanced mining sampling"}


def fit_cutoff(cal):
    s = np.asarray(cal["v2b_val"]["scores"], float)
    human = np.asarray(cal["v2b_val"]["kind"]) == "human"
    return float(np.quantile(s[human], 0.99))