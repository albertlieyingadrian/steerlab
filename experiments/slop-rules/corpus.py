"""Build the scored corpus: one window per text, human and AI, with its set, source, model, prompt group and split.

Sets:
  matched   EditLens + HC3 human texts and the 8 open models' replies to the same opening or question (decision set),
            plus a same-source pool of up to 600 more human texts per source (model "human-pool")
  closed    EditLens ai_generated by GPT-4.1, Claude Sonnet 4, Gemini 2.5 Flash; HC3 ChatGPT answers (transfer only)
  raid      RAID human texts (extra modern human genres) and RAID AI (GPT-4, ChatGPT, Mistral-7B, Llama-2-70B chat)
  classic   the 318 Gutenberg and Wikipedia passages behind the v1 band, and Qwen3-8B's 96 original replies
            from deslop-h2h (the setting the v1 rules were built in)

Writes ~/.cache/steerlab/slop-rules/corpus.jsonl and results/corpus_counts.json.
"""

from __future__ import annotations

import hashlib
import json
import random
import re
from collections import Counter

import pandas as pd

from common import (
    CACHE,
    CLASSIC,
    CORPUS,
    EDITLENS,
    GEN,
    H2H,
    HC3,
    OPEN_MODELS,
    RESULTS,
    SEED,
    detok,
    group_split,
    n_words,
    split_first_sentence,
    window,
    write_json,
    write_jsonl,
)

CLOSED = {
    "gpt-4.1-2025-04-14": "gpt-4.1",
    "claude-sonnet-4-20250514": "claude-sonnet-4",
    "gemini-2.5-flash": "gemini-2.5-flash",
}
PER_CLOSED, PER_RAID_AI, PER_POOL = 300, 400, 600


def _h(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()[:12]


def _norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", s.lower()).strip()


def strip_opening(text: str, opening: str) -> str:
    """Remove the given opening sentence when a model repeated it before continuing."""
    t = text.strip().lstrip('"“')
    if opening and _norm(t[: len(opening) + 5]).startswith(_norm(opening)):
        t = t[len(opening) :].lstrip(' "”\n')
    return t


def row(text: str, **kw: object) -> dict | None:
    w = window(text)
    if w is None:
        return None
    return {**kw, "text": w, "words": n_words(w)}


def matched() -> list[dict]:
    prompts = [json.loads(line) for line in (CACHE / "prompts.jsonl").read_text().split("\n") if line.strip()]
    gens = {}
    for m in OPEN_MODELS:
        path = GEN / f"{m.replace('/', '__')}.jsonl"
        if path.exists():
            gens[m] = {r["pid"]: r for r in map(json.loads, filter(None, path.read_text().split("\n")))}
    out = []
    for p in prompts:
        base = {
            "set": "matched",
            "regime": p["regime"],
            "source": p["source"],
            "group": p["group"],
            "split": group_split(p["group"]),
            "pid": p["pid"],
        }
        out.append(row(p["human"], side="human", model="human", **base))
        for m, g in gens.items():
            if p["pid"] in g:
                text = g[p["pid"]]["text"]
                if p["regime"] == "editlens":
                    text = strip_opening(text, p["opening"])
                out.append(row(text, side="ai", model=m.split("/")[1], **base))
        if p["regime"] == "hc3":
            out.append(row(p["chatgpt"], side="ai", model="chatgpt-hc3", **{**base, "set": "closed"}))
    return [r for r in out if r]


def human_pool(rng: random.Random) -> list[dict]:
    """More human texts from the same 11 sources (not the prompts' own texts), first sentence dropped; amendment 2."""
    prompts = [json.loads(line) for line in (CACHE / "prompts.jsonl").read_text().split("\n") if line.strip()]
    used = {p["group"] for p in prompts}
    out = []
    df = pd.concat([pd.read_csv(EDITLENS / f"{n}.csv") for n in ("test", "val", "test_enron")])
    df = df[df.text_type == "human_written"].drop_duplicates("source_id")
    for source, sub in df.groupby("source"):
        recs = sorted((str(r.source_id), str(r.text)) for r in sub.itertuples() if f"el:{r.source_id}" not in used)
        for sid, text in rng.sample(recs, min(PER_POOL, len(recs))):
            g = f"pool:el:{sid}"
            out.append(
                row(
                    split_first_sentence(text)[1],
                    side="human",
                    model="human-pool",
                    set="matched",
                    regime="editlens",
                    source=source,
                    group=g,
                    split=group_split(g),
                    pid=g,
                )
            )
    hc3 = [json.loads(line) for line in HC3.read_text().split("\n") if line.strip()]
    for source in sorted({r["source"] for r in hc3}):
        recs = []
        for r in hc3:
            qid = hashlib.sha256(r["question"].encode()).hexdigest()[:12]
            if r["source"] == source and r["human_answers"] and f"hc3:{source}:{qid}" not in used:
                recs.append((qid, detok(r["human_answers"][0])))
        recs.sort()
        for qid, text in rng.sample(recs, min(PER_POOL, len(recs))):
            g = f"pool:hc3:{qid}"
            out.append(
                row(
                    text,
                    side="human",
                    model="human-pool",
                    set="matched",
                    regime="hc3",
                    source=source,
                    group=g,
                    split=group_split(g),
                    pid=g,
                )
            )
    return [r for r in out if r]


def closed_editlens(rng: random.Random) -> list[dict]:
    df = pd.concat([pd.read_csv(EDITLENS / "test.csv"), pd.read_csv(EDITLENS / "test_enron.csv")])
    df = df[(df.text_type == "ai_generated") & df.model.isin(CLOSED)].drop_duplicates("text_id")
    out = []
    for model, sub in df.groupby("model"):
        recs = sorted(sub[["text_id", "text", "source"]].itertuples(index=False))
        for tid, text, source in rng.sample(recs, min(PER_CLOSED, len(recs))):
            g = f"elai:{tid}"
            out.append(
                row(
                    str(text),
                    side="ai",
                    model=CLOSED[model],
                    set="closed",
                    regime="editlens",
                    source=source,
                    group=g,
                    split=group_split(g),
                    pid=g,
                )
            )
    return [r for r in out if r]


def raid(rng: random.Random) -> list[dict]:
    df = pd.read_csv(EDITLENS / "raid_10k.csv")
    out = []
    for model, sub in df.groupby("model"):
        recs = sorted(sub[["text", "domain"]].itertuples(index=False))
        if model != "human":
            recs = rng.sample(recs, min(PER_RAID_AI, len(recs)))
        for text, domain in recs:
            g = f"raid:{_h(str(text))}"
            out.append(
                row(
                    str(text),
                    side="human" if model == "human" else "ai",
                    model=f"raid-{model}",
                    set="raid",
                    regime="raid",
                    source=f"raid_{domain}",
                    group=g,
                    split=group_split(g),
                    pid=g,
                )
            )
    return [r for r in out if r]


def classic() -> list[dict]:
    out = []
    for r in map(json.loads, filter(None, CLASSIC.read_text().split("\n"))):
        g = f"classic:{r['id']}"
        out.append(
            row(
                r["text"],
                side="human",
                model="human",
                set="classic",
                regime="classic",
                source=r["source"],
                group=g,
                split=group_split(g),
                pid=g,
            )
        )
    for r in map(json.loads, filter(None, H2H.read_text().split("\n"))):
        g = f"h2h:{r['id']}:{r['sample']}"
        out.append(
            row(
                r["text"],
                side="ai",
                model="qwen3-8b",
                set="classic",
                regime="classic",
                source="h2h_" + r["id"].split("-")[-1],
                group=g,
                split=group_split(g),
                pid=g,
            )
        )
    return [r for r in out if r]


def main() -> None:
    rng = random.Random(SEED)
    rows = matched() + human_pool(random.Random(SEED + 1)) + closed_editlens(rng) + raid(rng) + classic()
    for i, r in enumerate(rows):
        r["id"] = i
    write_jsonl(CORPUS, rows)
    counts: dict = {}
    for key in [("set", "side", "split"), ("set", "model"), ("set", "source", "side")]:
        c = Counter(" | ".join(str(r[k]) for k in key) for r in rows)
        counts[" x ".join(key)] = dict(sorted(c.items()))
    words = {
        s: round(
            sum(r["words"] for r in rows if r["set"] == "matched" and r["side"] == s)
            / max(1, sum(1 for r in rows if r["set"] == "matched" and r["side"] == s)),
            1,
        )
        for s in ("human", "ai")
    }
    counts["matched mean window words"] = words
    write_json(RESULTS / "corpus_counts.json", counts)
    print(f"{len(rows)} windows -> {CORPUS}")
    print(json.dumps(counts["set x side x split"], indent=1), words)


if __name__ == "__main__":
    main()
