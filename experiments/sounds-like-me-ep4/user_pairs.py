"""Freeze the user's blind rating set: 150 held-out draft pairs (30 writers x 5) + 10 swapped repeats.

    python user_pairs.py

Drafts come from Episode 1/2 held-out arms for the same writer and the same synthetic brief. Broken drafts (loops,
counting runs, < 30 words) are excluded so the choice is about voice, not breakage. Seeded; the set's hash goes in
the run log before the page is built.

Writes: data/local/user_pairs.json (text + arms; gitignored), rate/pairs.js (display text only, no arms; gitignored),
results/user_pairs_index.json (pair ids, writer pseudonyms, briefs, arms, A/B sides, the hash; no text).
"""

import hashlib
import itertools
import json
import random
import re
import sys
from collections import Counter

from common4 import EP2, HERE, LOCAL, RES, SEED, dump

sys.path.append(str(EP2))
from common import authors, briefs, texts  # Episode 1
from score_ep2 import broken  # Episode 2's loop / degenerate rule

ARMS = [
    "R1_prompt",
    "R1b_bon",
    "R2_harness",
    "R3_voice",
    "R4_persona",
    "G2_gemini_harness",
    "ep1-gemini-edits",
    "ep1-llamabase-k3",
    "ep1-sonnet-note",
    "ep1-qwen8b-k0",
]
PER_WRITER, N_REPEAT = 5, 10
EXTRA_NAMES = ["Lauren", "Tamiathen", "James S."]  # Episode 2's hand-reviewed copied names


def redact(text, author):
    """Episode 2's redaction: the writer's name parts and initials, plus hand-found copied names."""
    for n in EXTRA_NAMES:
        text = re.sub(rf"\b{re.escape(n)}", "[name]", text)
    parts = [p for p in re.split(r"\W+", author) if len(p) >= 3]
    initials = "".join(p[0] for p in parts if p[0].isupper())
    for p in sorted(parts, key=len, reverse=True):
        text = re.sub(rf"\b{re.escape(p)}\b", "[name]", text, flags=re.IGNORECASE)
    if len(initials) >= 2:
        text = re.sub(rf"\b{re.escape(initials)}\b", "[name]", text, flags=re.IGNORECASE)
    return text


def main():
    rnd = random.Random(SEED)
    drafts = {}
    for arm in ARMS:
        for r in json.loads((EP2 / "results/scored" / f"{arm}__heldout.json").read_text())["drafts"]:
            if r["text"].strip() and len(r["text"].split()) >= 30 and not broken(r):
                drafts[(arm, r["author"], r["brief"])] = r["text"]
    held = [a for a in authors()["authors"] if a["split"] == "heldout"]
    rnd.shuffle(held)
    bl = briefs()
    B = {b["id"]: b for b in (bl["briefs"] if isinstance(bl, dict) else bl)}
    combos = list(itertools.combinations(ARMS, 2))
    use = Counter()
    pairs = []
    for wi, a in enumerate(held):
        name = a["author"]
        bset = sorted({k[2] for k in drafts if k[1] == name})
        cand = [(x, y, b) for (x, y) in combos for b in bset if (x, name, b) in drafts and (y, name, b) in drafts]
        chosen = []
        for _ in range(PER_WRITER):
            # balance arms across the set; never repeat an arm pair for one writer
            done = {(d[0], d[1]) for d in chosen}
            cand = [c for c in cand if (c[0], c[1]) not in done]
            w = [1.0 / (1 + use[c[0]] + use[c[1]]) ** 2 for c in cand]
            c = rnd.choices(cand, weights=w)[0]
            chosen.append(c)
            use[c[0]] += 1
            use[c[1]] += 1
        refs = [redact(t, name) for t in texts(a, "profile")[:3]]
        for x, y, b in chosen:
            if rnd.random() < 0.5:
                x, y = y, x
            pairs.append(
                dict(
                    writer=f"Writer {wi + 1:02d}",
                    author=name,
                    brief=b,
                    situation=B[b].get("situation", ""),
                    arm_a=x,
                    arm_b=y,
                    a=redact(drafts[(x, name, b)], name),
                    b=redact(drafts[(y, name, b)], name),
                    refs=refs,
                    repeat_of=None,
                )
            )
    rnd.shuffle(pairs)
    for i, p in enumerate(pairs):
        p["pair"] = f"p{i + 1:03d}"
    # 10 repeats, sides swapped, each shown 30-39 places after its original
    reps = rnd.sample([p for p in pairs if int(p["pair"][1:]) <= len(pairs) - 40], N_REPEAT)
    seq = list(pairs)
    for j, p in enumerate(reps):
        q = dict(p, pair=f"r{j + 1:02d}", repeat_of=p["pair"], arm_a=p["arm_b"], arm_b=p["arm_a"], a=p["b"], b=p["a"])
        seq.insert(min(seq.index(p) + 30 + rnd.randrange(10), len(seq)), q)
    digest = hashlib.sha256(json.dumps(seq, sort_keys=True).encode()).hexdigest()[:16]
    dump(LOCAL / "user_pairs.json", seq)
    show = [
        dict(id=p["pair"], writer=p["writer"], situation=p["situation"], refs=p["refs"], a=p["a"], b=p["b"])
        for p in seq
    ]
    (HERE / "rate").mkdir(exist_ok=True)
    (HERE / "rate" / "pairs.js").write_text(
        "// Generated by user_pairs.py. Local only (gitignored): public writers' emails and model drafts.\n"
        f"window.SET = {json.dumps(dict(hash=digest, n=len(show), pairs=show))};\n"
    )
    dump(
        RES / "user_pairs_index.json",
        dict(
            hash=digest,
            n_pairs=len(pairs),
            n_repeats=N_REPEAT,
            arms_used=dict(use),
            pairs=[{k: p[k] for k in ("pair", "writer", "brief", "arm_a", "arm_b", "repeat_of")} for p in seq],
        ),
    )
    print("pairs", len(pairs), "repeats", N_REPEAT, "hash", digest, "arm use", dict(use))


if __name__ == "__main__":
    main()
