"""The note's report/data.js: aggregate numbers only (no dataset text, no participant ids).

python export_pages.py
"""

import json

from common4 import HERE, RES

S = json.loads((RES / "summary.json").read_text())
P = json.loads((RES / "predictions.json").read_text())
H1, H2, H3 = S["h1"]["heldout"], S["h2"]["heldout"], S["h3"]["heldout"]

RULERS = [
    ("luar", "LUAR voice similarity", "series"),
    ("spec", "LUAR specificity", "series"),
    ("pref", "Preference model (Ep 2)", "series"),
    ("detector_neg", "Detector", "series"),
    ("panel", "LLM panel (mean of 3)", "panel"),
    ("panel_qwen3-32b", "Qwen3-32B", "panel"),
    ("panel_gemma-3-27b", "Gemma-3-27B", "panel"),
    ("panel_llama-3.1-8b", "Llama-3.1-8B", "panel"),
    ("tfidf_char", "Character n-grams", "baseline"),
    ("tfidf_word", "Word overlap", "baseline"),
    ("length", "Length", "baseline"),
]


def pick(d, k):
    v = d.get(k)
    return v if isinstance(v, list) and len(v) == 3 else None


def h3key(k):
    return {"pref": "pref_neg", "detector_neg": "detector"}.get(k, k)


metrics = {
    "h1_r": dict(
        label="Own voice: within-person correlation with the writer's 1-5 rating (H1)",
        chance=0.0,
        lo=-0.1,
        hi=0.6,
        v={k: pick(H1["rm_r"], k) for k, *_ in RULERS},
    ),
    "h1_up": dict(
        label="Writer rated the edit higher: share where the ruler agrees (H1)",
        chance=0.5,
        lo=0.3,
        hi=1.0,
        v={k: pick(H1["pairwise_up"], k) for k, *_ in RULERS},
    ),
    "h1_eq": dict(
        label="Writer rated both the same: share where the ruler still prefers the edit (H1)",
        chance=0.5,
        lo=0.3,
        hi=1.0,
        v={k: pick(H1["prefers_edit_equal"], k) for k, *_ in RULERS},
    ),
    "h2": dict(
        label="Fiction style triplets: agreement with the crowd majority (H2)",
        chance=0.5,
        lo=0.4,
        hi=0.75,
        v={k: pick(H2["acc"], k) for k, *_ in RULERS},
    ),
    "h3": dict(
        label="News articles: AUROC against five experts' human/AI vote (H3)",
        chance=0.5,
        lo=0.2,
        hi=1.02,
        v={k: pick(H3["auroc_majority"], h3key(k)) for k, *_ in RULERS},
    ),
    "h3_ai": dict(
        label="AI-written articles only: Spearman with how sure the experts were (H3)",
        chance=0.0,
        lo=-0.6,
        hi=0.65,
        v={k: pick(H3["spearman_signed_within_ai"], h3key(k)) for k, *_ in RULERS},
    ),
}
out = dict(
    rulers=[dict(key=k, name=n, kind=t) for k, n, t in RULERS],
    metrics=metrics,
    counts=dict(
        h1_people=H1["n_people"],
        h1_tasks=H1["n_tasks"],
        h1_up=H1["n_up"],
        h1_equal=H1["n_equal"],
        h1_down=H1["n_down"],
        h2_n=H2["n"],
        h2_high=H2["n_high"],
        h3_n=H3["n"],
    ),
    predictions=P,
    user=S["user"],
)
(HERE / "report" / "data.js").write_text(
    f"// Generated by export_pages.py from results/. Aggregates only.\nwindow.EP4 = {json.dumps(out)};\n"
)
print("data.js", len(json.dumps(out)), "bytes")
