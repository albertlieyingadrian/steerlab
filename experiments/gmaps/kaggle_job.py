"""Fine-tuning on Kaggle's free GPUs (Tinker dropped 2026-11-11: no budget). Builds the private dataset and the kernels.

    kaggle_job.py dataset                 # data/kaggle/dataset/: chat records for the mixes, dev and test (private)
    kaggle_job.py train --base unsloth/Qwen3-14B-unsloth-bnb-4bit --mix pfa --epochs 2 --name q14-pfa
    kaggle_job.py infer --run q14-pfa --ckpt epoch2 --split test   # one test run per final system
    kaggle_job.py fetch --slug gmaps-q14-pfa     # kernel output -> results/kaggle/<slug>/, preds -> results/runs/

The kernels are private, GPU (T4/P100, 16 GB), internet on (pip install unsloth, model download). ATCO2 text only
ever leaves the laptop inside a PRIVATE Kaggle dataset (research licence). Fine-tuned arms use a short system prompt
(`atc.SYSTEM_FT`, about 40 tokens), which cuts training tokens about 3x; prompted arms keep `atc.SYSTEM`.
Training rows follow the data rules in the train.py docstring: no Prague data, no Claude or GPT outputs.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess

import atc
import external

KDIR = atc.DATA / "kaggle"
DSET = KDIR / "dataset"
DSET_SLUG = "gmaps-atco2-private"
KAGGLE = os.path.expanduser("~/.local/bin/kaggle")


def env() -> dict:
    import sys

    sys.path.insert(0, str(atc.HERE.parent / "fin-llm"))
    import fin

    fin.load_env()
    e = dict(os.environ)
    e["KAGGLE_API_TOKEN"] = e.get("KAGGLE_API_KEY", "")
    return e


def kaggle(*args: str, check: bool = True) -> str:
    r = subprocess.run([KAGGLE, *args], check=False, capture_output=True, text=True, env=env())
    if check and r.returncode != 0:
        raise SystemExit(f"kaggle {' '.join(args[:2])} failed: {r.stderr[-500:]}")
    return r.stdout + r.stderr


def user() -> str:
    """The Kaggle account name, from KAGGLE_USERNAME or the CLI's own config."""
    if os.environ.get("KAGGLE_USERNAME"):
        return os.environ["KAGGLE_USERNAME"]
    for line in kaggle("config", "view", check=False).splitlines():
        if line.strip().lstrip("- ").startswith("username:"):
            return line.split(":", 1)[1].strip()
    raise SystemExit("set KAGGLE_USERNAME")


def record(row: dict, with_answer: bool) -> dict:
    out = {"id": row["id"], "messages": atc.messages(row, [], atc.SYSTEM_FT)}
    if with_answer:
        out["answer"] = row.get("answer") or json.dumps(atc.target(row), ensure_ascii=False)
    return out


def dataset() -> None:
    DSET.mkdir(parents=True, exist_ok=True)
    for mix in ("pf", "pfa", "pfr"):
        rows = atc.read_jsonl(atc.DATA / "sft" / f"{mix}.jsonl")
        atc.write_jsonl(DSET / f"train_{mix}.jsonl", [record(r, True) for r in rows])
    pool = atc.read_jsonl(atc.SPLITS / "train.jsonl") + atc.read_jsonl(
        external.RB
    )  # RFT / GRPO prompts with gold (no flip augmentation)
    atc.write_jsonl(DSET / "rft_pool.jsonl", [{**record(r, False), "row": r} for r in pool])
    shutil.copy(atc.HERE / "atc.py", DSET / "atc.py")  # the scorer, for the RFT filter and the GRPO reward
    atc.write_jsonl(DSET / "dev.jsonl", [record(r, False) for r in atc.load("dev")])
    atc.write_jsonl(DSET / "test.jsonl", [record(r, False) for r in atc.load("test")])  # hash-checked by atc.load
    meta = {
        "title": "gmaps atco2 private",
        "id": f"{user()}/{DSET_SLUG}",
        "licenses": [{"name": "other"}],
        "isPrivate": True,
    }
    (DSET / "dataset-metadata.json").write_text(json.dumps(meta, indent=1))
    if DSET_SLUG in kaggle("datasets", "list", "--mine", check=False):
        print(kaggle("datasets", "version", "-p", str(DSET), "-m", "update", "-q", "-r", "skip")[-300:])
    else:
        print(kaggle("datasets", "create", "-p", str(DSET), "-q", "-r", "skip")[-300:])


KERNEL = r'''
# GMAPS replication: Unsloth QLoRA on Kaggle. Generated by experiments/gmaps/kaggle_job.py; do not edit by hand.
import glob, json, os, subprocess, sys, time
CFG = json.loads("""__CFG__""")
t0 = time.time()
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "unsloth"], check=True)
from unsloth import FastLanguageModel  # noqa: E402
import torch  # noqa: E402
from datasets import Dataset  # noqa: E402

D = os.path.dirname(glob.glob("/kaggle/input/**/dev.jsonl", recursive=True)[0])
OUT = "/kaggle/working"
print("data dir", D, "gpus", torch.cuda.device_count(), torch.cuda.get_device_name(0), flush=True)
def adapter_dir(path):
    """Kernel outputs mount under /kaggle/input in a layout that varies; find the adapter by its config file."""
    if os.path.exists(f"{path}/adapter_config.json"):
        return path
    hits = glob.glob(f"/kaggle/input/**/{os.path.basename(path)}/adapter_config.json", recursive=True)
    print("adapter search", path, hits, flush=True)
    return os.path.dirname(hits[0])

def rows(name):
    with open(f"{D}/{name}.jsonl") as f:
        return [json.loads(l) for l in f if l.strip()]

model, tok = FastLanguageModel.from_pretrained(CFG["base"], max_seq_length=CFG["max_len"], load_in_4bit=True)
def prompt(r):
    return tok.apply_chat_template(r["messages"], tokenize=False, add_generation_prompt=True, enable_thinking=False)

def generate(split, tag):
    FastLanguageModel.for_inference(model)
    tok.padding_side = "left"
    data, out = rows(split), []
    for i in range(0, len(data), CFG["gen_batch"]):
        chunk = data[i:i + CFG["gen_batch"]]
        enc = tok([prompt(r) for r in chunk], return_tensors="pt", padding=True, add_special_tokens=False).to("cuda")
        with torch.no_grad():
            g = model.generate(**enc, max_new_tokens=200, do_sample=False, repetition_penalty=1.0,
                               pad_token_id=tok.pad_token_id)
        for r, seq in zip(chunk, g[:, enc["input_ids"].shape[1]:]):
            text = tok.decode(seq, skip_special_tokens=True).split("</think>")[-1].strip()
            out.append({"id": r["id"], "output": text})
    with open(f"{OUT}/{split}__{tag}.jsonl", "w") as f:
        f.writelines(json.dumps(o) + "\n" for o in out)
    print(f"[{time.time() - t0:.0f}s] wrote {split}__{tag} ({len(out)})", flush=True)

if CFG["mode"] == "train":
    from trl import SFTConfig, SFTTrainer
    from transformers import TrainerCallback
    model = FastLanguageModel.get_peft_model(model, r=CFG["rank"], lora_alpha=CFG["rank"], lora_dropout=0,
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
        use_gradient_checkpointing="unsloth", random_state=0)
    train = Dataset.from_list([{"prompt": prompt(r), "completion": r["answer"] + "<|im_end|>"}
                               for r in rows("train_" + CFG["mix"])])
    class EpochEval(TrainerCallback):
        def on_epoch_end(self, args, state, control, **kw):
            ep = round(state.epoch)
            model.save_pretrained(f"{OUT}/epoch{ep}")
            generate("dev", f"{CFG['name']}-e{ep}")
            FastLanguageModel.for_training(model)
            tok.padding_side = "right"
        def on_log(self, args, state, control, logs=None, **kw):
            print(f"[{time.time() - t0:.0f}s] step {state.global_step}/{state.max_steps} {logs}", flush=True)
    cfg = SFTConfig(output_dir=f"{OUT}/ckpt", per_device_train_batch_size=CFG["batch"],
        gradient_accumulation_steps=CFG["accum"], num_train_epochs=CFG["epochs"], learning_rate=CFG["lr"],
        lr_scheduler_type="linear", warmup_steps=10, logging_steps=20, save_strategy="no", fp16=True,
        optim="adamw_8bit", max_length=CFG["max_len"], completion_only_loss=True, report_to="none", seed=0,
        dataset_num_proc=2)
    trainer = SFTTrainer(model=model, processing_class=tok, train_dataset=train, args=cfg, callbacks=[EpochEval()])
    trainer.train()
    with open(f"{OUT}/train_log.json", "w") as f:
        json.dump(trainer.state.log_history, f)
elif CFG["mode"] == "rft":
    # Stage 2: sample k answers per train row from the SFT adapter, keep the shortest one the scorer marks fully
    # right (the model's own wording), then one more SFT epoch on those, continuing the same adapter.
    from peft import PeftModel
    from trl import SFTConfig, SFTTrainer
    sys.path.insert(0, D)
    import atc
    model = PeftModel.from_pretrained(model, adapter_dir(CFG["adapter"]), is_trainable=True)
    FastLanguageModel.for_inference(model)
    tok.padding_side = "left"
    pool, kept, rates = rows("rft_pool"), [], []
    for i in range(0, len(pool), CFG["rft_batch"]):
        chunk = pool[i:i + CFG["rft_batch"]]
        enc = tok([prompt(r) for r in chunk], return_tensors="pt", padding=True, add_special_tokens=False).to("cuda")
        with torch.no_grad():
            g = model.generate(**enc, max_new_tokens=200, do_sample=True, temperature=1.0, top_p=1.0,
                               num_return_sequences=CFG["k"], pad_token_id=tok.pad_token_id)
        g = g[:, enc["input_ids"].shape[1]:]
        for j, r in enumerate(chunk):
            outs = [tok.decode(s, skip_special_tokens=True).split("</think>")[-1].strip()
                    for s in g[j * CFG["k"]:(j + 1) * CFG["k"]]]
            ok = [o for o in outs if atc.score_row(r["row"], o)["full"]]
            rates.append(len(ok) / len(outs))
            if ok:
                kept.append({"prompt": prompt(r), "completion": min(ok, key=len) + "<|im_end|>"})
        if i % (CFG["rft_batch"] * 25) == 0:
            print(f"[{time.time() - t0:.0f}s] rft {i}/{len(pool)} kept {len(kept)}", flush=True)
    summary = {"rows": len(pool), "k": CFG["k"], "pass@1": sum(rates) / len(rates), "solved": len(kept)}
    print(summary, flush=True)
    json.dump(summary, open(f"{OUT}/rft_summary.json", "w"))
    FastLanguageModel.for_training(model)
    tok.padding_side = "right"
    cfg = SFTConfig(output_dir=f"{OUT}/ckpt", per_device_train_batch_size=CFG["batch"],
        gradient_accumulation_steps=CFG["accum"], num_train_epochs=1, learning_rate=CFG["lr"],
        lr_scheduler_type="linear", warmup_steps=5, logging_steps=10, save_strategy="no", fp16=True,
        optim="adamw_8bit", max_length=CFG["max_len"], completion_only_loss=True, report_to="none", seed=0)
    SFTTrainer(model=model, processing_class=tok, train_dataset=Dataset.from_list(kept), args=cfg).train()
    model.save_pretrained(f"{OUT}/rft")
    generate("dev", f"{CFG['name']}")
elif CFG["mode"] == "grpo":
    # Stage 3: GRPO from the adapter; reward = 1 for a full-record match, else 0.1 per correct part (role,
    # callsigns, action set), 0 for unparseable JSON. Logged per step so reward hacking shows (JSON validity, length).
    from peft import PeftModel
    from trl import GRPOConfig, GRPOTrainer
    sys.path.insert(0, D)
    import atc
    model = PeftModel.from_pretrained(model, adapter_dir(CFG["adapter"]), is_trainable=True)
    pool = rows("rft_pool")
    data = Dataset.from_list([{"prompt": prompt(r), "row": json.dumps(r["row"])} for r in pool]).shuffle(seed=7)
    def reward(prompts, completions, row, **kw):
        out = []
        for c, rj in zip(completions, row):
            s = atc.score_row(json.loads(rj), c.split("</think>")[-1])
            out.append(0.0 if not s["valid"] else 1.0 if s["full"] else
                       0.1 * ((s["role_ok"] is not False) + s["cs_ok"] + s["act_ok"]))
        return out
    cfg = GRPOConfig(output_dir=f"{OUT}/ckpt", per_device_train_batch_size=CFG["batch"],
        gradient_accumulation_steps=1, num_generations=CFG["k"], max_completion_length=200,
        max_prompt_length=CFG["max_len"], learning_rate=CFG["lr"], max_steps=CFG["steps"], temperature=1.0,
        logging_steps=1, save_strategy="no", fp16=True, optim="adamw_8bit", report_to="none", seed=0)
    trainer = GRPOTrainer(model=model, processing_class=tok, reward_funcs=[reward], args=cfg, train_dataset=data)
    trainer.train()
    json.dump(trainer.state.log_history, open(f"{OUT}/grpo_log.json", "w"))
    model.save_pretrained(f"{OUT}/grpo")
    generate("dev", f"{CFG['name']}")
else:
    from peft import PeftModel
    model = PeftModel.from_pretrained(model, adapter_dir(CFG["adapter"]))
    generate(CFG["split"], CFG["name"])
print(f"done in {time.time() - t0:.0f}s", flush=True)
'''


def push(slug: str, cfg: dict, sources: list[str]) -> None:
    kdir = KDIR / "kernels" / slug
    if kdir.exists():
        shutil.rmtree(kdir)
    kdir.mkdir(parents=True)
    (kdir / "job.py").write_text(KERNEL.replace("__CFG__", json.dumps(cfg)))
    meta = {
        "id": f"{user()}/{slug}",
        "title": slug,
        "code_file": "job.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": [f"{user()}/{DSET_SLUG}"],
        "kernel_sources": sources,
    }
    (kdir / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    print(kaggle("kernels", "push", "-p", str(kdir), "--accelerator", "NvidiaTeslaT4")[-400:])


def train(base: str, mix: str, epochs: int, name: str, lr: float, rank: int) -> None:
    cfg = {
        "mode": "train",
        "base": base,
        "mix": mix,
        "epochs": epochs,
        "name": name,
        "lr": lr,
        "rank": rank,
        "batch": 8,
        "accum": 2,
        "max_len": 512,
        "gen_batch": 16,
    }
    push(f"gmaps-{name}", cfg, [])


def infer(run_name: str, ckpt: str, split: str, base: str) -> None:
    if split == "test":
        import run as runmod

        runmod.claim_test(f"{run_name}-{ckpt}")
    cfg = {
        "mode": "infer",
        "base": base,
        "adapter": f"/kaggle/input/gmaps-{run_name}/{ckpt}",
        "split": split,
        "name": f"{run_name}-{ckpt}",
        "max_len": 512,
        "gen_batch": 16,
    }
    push(f"gmaps-{run_name}-{ckpt}-{split}", cfg, [f"{user()}/gmaps-{run_name}"])


def stage(mode: str, run_name: str, ckpt: str, name: str, base: str, lr: float, k: int, steps: int) -> None:
    """RFT (mode rft) or GRPO (mode grpo) continuing the adapter `ckpt` of kernel run `run_name`."""
    cfg = {
        "mode": mode,
        "base": base,
        "adapter": f"/kaggle/input/gmaps-{run_name}/{ckpt}",
        "name": name,
        "lr": lr,
        "k": k,
        "steps": steps,
        "batch": 8,
        "accum": 2,
        "max_len": 512,
        "gen_batch": 16,
        "rft_batch": 4,
    }
    push(f"gmaps-{name}", cfg, [f"{user()}/gmaps-{run_name}"])


def fetch(slug: str) -> None:
    out = atc.RESULTS / "kaggle" / slug
    out.mkdir(parents=True, exist_ok=True)
    print(kaggle("kernels", "output", f"{user()}/{slug}", "-p", str(out), "--force")[-300:])
    for f in out.glob("*__*.jsonl"):
        shutil.copy(f, atc.RESULTS / "runs" / f.name)
        print("copied", f.name)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=["dataset", "train", "infer", "fetch", "status", "rft", "grpo"])
    ap.add_argument("--k", type=int, default=8)
    ap.add_argument("--steps", type=int, default=60)
    ap.add_argument("--base", default="unsloth/Qwen3-14B-unsloth-bnb-4bit")
    ap.add_argument("--mix", default="pfa")
    ap.add_argument("--epochs", type=int, default=2)
    ap.add_argument("--lr", type=float, default=2e-4)
    ap.add_argument("--rank", type=int, default=32)
    ap.add_argument("--name")
    ap.add_argument("--run")
    ap.add_argument("--ckpt", default="epoch2")
    ap.add_argument("--split", default="dev")
    ap.add_argument("--slug")
    a = ap.parse_args()
    if a.step == "dataset":
        dataset()
    elif a.step == "train":
        train(a.base, a.mix, a.epochs, a.name, a.lr, a.rank)
    elif a.step == "infer":
        infer(a.run, a.ckpt, a.split, a.base)
    elif a.step in ("rft", "grpo"):
        stage(a.step, a.run, a.ckpt, a.name, a.base, a.lr, a.k, a.steps)
    elif a.step == "fetch":
        fetch(a.slug)
    else:
        print(kaggle("kernels", "status", f"{user()}/{a.slug}"))


if __name__ == "__main__":
    main()
