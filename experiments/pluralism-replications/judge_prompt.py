"""The Artificial Hivemind paper's "Overall Quality" judge prompt (arXiv 2510.22954, Figure 23) and a score parser."""

from __future__ import annotations

import json
import re

TEMPLATE = """You are tasked with evaluating the quality of a model's response. For this task, you will receive the following components:
[user_request]: A user request provided to the model.
[model_response]: The response generated by the model.
[evaluation_rubric]: A set of fine-grained criteria for assessing the response.
Your objective is to analyze how well the model's response aligns with the user request regarding the evaluation rubric. For each criterion in the rubric:
- Assign a score from 1 to 5 (where 5 is the highest quality).
- Provide a concise explanation of your reasoning for the assigned score.
Here's a concrete example:
[User Request]: Write a pun about cats.
[Model Response]: I'm feline good about this!
[Evaluation Rubric]:
- Overall Quality: Does the response have overall high quality for achieving the user's goal?
[Output]:
{
"Overall Quality": {
"score": 5,
"reason": "The response is of excellent quality, fully meeting or exceeding the user's expectations with highly relevant, accurate, and comprehensive information."
}
}
Now let's begin the task. Please evaluate the model response as demonstrated above. Ensure your scores and reasoning are objective and align with the rubric.
[User Request]: {USER_REQUEST}
[Model Response]: {MODEL_RESPONSE}
[Evaluation Rubric]:
- Overall Quality: Does the response have overall high quality for achieving the user's goal?
[Output]:
"""


def overall_prompt(user_request: str, model_response: str) -> str:
    return TEMPLATE.replace("{USER_REQUEST}", user_request).replace("{MODEL_RESPONSE}", model_response)


def parse_score(text: str) -> int | None:
    """First 1-5 score in the judge's JSON (or a bare '"score": N'); None if absent."""
    if not text:
        return None
    try:
        start, end = text.index("{"), text.rindex("}") + 1
        obj = json.loads(text[start:end])
        s = obj.get("Overall Quality", obj).get("score")
        if s is not None and 1 <= int(s) <= 5:
            return int(s)
    except (ValueError, AttributeError, TypeError, json.JSONDecodeError):
        pass
    for pat in (r'"?score"?\s*[:=]\s*"?([1-5])', r"score (?:is|of)\s*\**([1-5])\b", r"\[RESULT\]\s*([1-5])"):
        m = re.search(pat, text, re.I)
        if m:
            return int(m.group(1))
    return None
